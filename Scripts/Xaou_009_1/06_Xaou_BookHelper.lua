function Xaou_BookShow(msg, title)
    if Xaou_Show ~= nil then
        Xaou_Show(tostring(msg or ""), title or "คัมภีร์")
    elseif world ~= nil and world.ShowMsgBox ~= nil then
        world:ShowMsgBox(tostring(msg or ""), title or "คัมภีร์")
    else
        print("[XaouBook] " .. tostring(msg or ""))
    end
end

function Xaou_BookCleanText(text)
    text = tostring(text or "")
    text = string.gsub(text, "^%d+%.%s*", "")
    return text
end

function Xaou_MatchBookCommand(book, keyword)
    keyword = tostring(keyword or "")
    if keyword == "" or keyword == "ค้นหา ID/ชื่อ" then return true end
    keyword = string.lower(keyword)
    if book == nil then return false end
    if string.find(string.lower(tostring(book.text or "")), keyword, 1, true) then return true end
    if string.find(string.lower(tostring(book.id or "")), keyword, 1, true) then return true end
    if string.find(string.lower(tostring(book.cat or "")), keyword, 1, true) then return true end
    if string.find(string.lower(tostring(book.sourceStory or "")), keyword, 1, true) then return true end
    return false
end

function Xaou_GetBookList(category, keyword)
    local result = {}
    category = tostring(category or "ทั้งหมด")
    for _, book in ipairs(Xaou_BookList or {}) do
        local okCat = (category == "" or category == "ทั้งหมด" or tostring(book.cat or "") == category)
        if okCat and Xaou_MatchBookCommand(book, keyword) then
            table.insert(result, book)
        end
    end
    return result
end
